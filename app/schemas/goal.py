from __future__ import annotations

from datetime import datetime
from enum import Enum
from typing import Optional
from pydantic import BaseModel, ConfigDict, EmailStr, Field


class GoalStatusEnum(str, Enum):
    ACTIVE = "active"
    INACTIVE = "inactive"


class GoalCreate(BaseModel):
    measure_type: str = Field(
        ...,
        min_length=1,
        max_length=100,
        description="Measurement unit type for the goal (e.g. `minutes`, `hours`, `points`, `tasks`)",
        examples=["minutes"],
    )
    status: GoalStatusEnum = Field(
        default=GoalStatusEnum.ACTIVE,
        description="Goal status (`active` or `inactive`)",
        examples=["active"],
    )
    email_parent: EmailStr = Field(
        ...,
        description="Email address of the parent/guardian who owns the goal",
        examples=["parent@fhk.app"],
    )
    name: str = Field(
        ...,
        min_length=1,
        max_length=255,
        description="Descriptive name of the goal",
        examples=["Daily reading"],
    )
    value: int = Field(
        ...,
        ge=0,
        description="Target numeric value for the goal",
        examples=[30],
    )


class GoalUpdate(BaseModel):
    name: Optional[str] = Field(
        default=None,
        min_length=1,
        max_length=255,
        description="New descriptive name of the goal",
        examples=["Evening reading"],
    )
    measure_type: Optional[str] = Field(
        default=None,
        min_length=1,
        max_length=100,
        description="New measurement unit type for the goal",
        examples=["minutes"],
    )
    value: Optional[int] = Field(
        default=None,
        ge=0,
        description="New target numeric value for the goal",
        examples=[45],
    )
    status: Optional[GoalStatusEnum] = Field(
        default=None,
        description="New goal status (`active` or `inactive`)",
        examples=["inactive"],
    )


class GoalResponse(BaseModel):
    id: int = Field(..., description="Unique database ID of the goal")
    created_at: datetime = Field(..., description="Creation UTC timestamp auto-generated by the backend")
    measure_type: str = Field(..., description="Measurement unit type of the goal")
    status: GoalStatusEnum = Field(..., description="Current goal status (`active` or `inactive`)")
    email_parent: EmailStr = Field(..., description="Parent/guardian email address")
    name: str = Field(..., description="Goal name")
    value: int = Field(..., description="Target numeric value of the goal")
    parent_id: int = Field(..., description="Foreign key ID linking to the parent account in `users`")
    updated_at: datetime = Field(..., description="Last update UTC timestamp")

    model_config = ConfigDict(from_attributes=True)


class GoalDeleteResponse(BaseModel):
    message: str = Field(
        ...,
        description="Deletion confirmation message",
        examples=["Goal deleted successfully."],
    )
    goal_id: int = Field(..., description="ID of the deleted goal", examples=[1])
