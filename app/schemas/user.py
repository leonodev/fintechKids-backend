from __future__ import annotations

from datetime import datetime
from typing import Optional
from pydantic import BaseModel, ConfigDict, EmailStr, Field


class UserCreate(BaseModel):
    name_family: str = Field(
        ...,
        min_length=1,
        max_length=255,
        description="Family name",
        examples=["Leon Family"],
    )
    email_parent: EmailStr = Field(
        ...,
        description="Parent or guardian email address",
        examples=["parent@fhk.app"],
    )
    password: str = Field(
        ...,
        min_length=4,
        max_length=512,
        description="Client-encrypted password from the app (same value used in `/auth/login`)",
        examples=["e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"],
    )
    approve_pin: str = Field(
        ...,
        min_length=4,
        max_length=50,
        description="Parental approval PIN",
        examples=["1234"],
    )


class UserUpdate(BaseModel):
    name_family: Optional[str] = Field(
        default=None,
        min_length=1,
        max_length=255,
        description="New family name",
    )
    password: Optional[str] = Field(
        default=None,
        min_length=4,
        max_length=512,
        description="New client-encrypted password from the app",
    )
    approve_pin: Optional[str] = Field(
        default=None,
        min_length=4,
        max_length=50,
        description="New parental approval PIN",
    )


class UserResponse(BaseModel):
    id: int = Field(..., description="Unique database record ID")
    created_at: datetime = Field(..., description="Registration UTC timestamp auto-generated by the backend")
    name_family: str = Field(..., description="Family name")
    email_parent: EmailStr = Field(..., description="Parent/guardian email address")
    approve_pin: str = Field(..., description="Parental approval PIN")
    is_active: bool = Field(..., description="Indicates whether the account is active")
    updated_at: datetime = Field(..., description="Last update UTC timestamp")

    model_config = ConfigDict(from_attributes=True)
