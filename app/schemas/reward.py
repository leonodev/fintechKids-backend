from __future__ import annotations

from datetime import datetime
from typing import Optional
from pydantic import AliasChoices, BaseModel, ConfigDict, EmailStr, Field


class RewardCreate(BaseModel):
    name: str = Field(
        ...,
        min_length=1,
        max_length=255,
        description="Name of the reward created by the parent",
        examples=["1 hour of video games"],
    )
    time_required: str = Field(
        ...,
        min_length=1,
        max_length=100,
        validation_alias=AliasChoices("time_required", "time_requiered"),
        description="Time required to claim the reward",
        examples=["01:00:00"],
    )
    coins_required: int = Field(
        ...,
        ge=0,
        description="Amount of coins required to claim the reward",
        examples=[100],
    )
    email_parent: EmailStr = Field(
        ...,
        description="Email address of the parent/guardian who owns the reward",
        examples=["parent@fhk.app"],
    )


class RewardUpdate(BaseModel):
    name: Optional[str] = Field(
        default=None,
        min_length=1,
        max_length=255,
        description="New reward name",
        examples=["2 hours of video games"],
    )
    time_required: Optional[str] = Field(
        default=None,
        min_length=1,
        max_length=100,
        validation_alias=AliasChoices("time_required", "time_requiered"),
        description="New time required for the reward",
        examples=["02:00:00"],
    )
    coins_required: Optional[int] = Field(
        default=None,
        ge=0,
        description="New amount of required coins",
        examples=[180],
    )


class RewardResponse(BaseModel):
    id: int = Field(..., description="Unique database ID of the reward")
    created_at: datetime = Field(..., description="Creation UTC timestamp auto-generated by the backend")
    name: str = Field(..., description="Reward name")
    time_required: str = Field(..., description="Required time for the reward")
    coins_required: int = Field(..., description="Required coins for the reward")
    email_parent: EmailStr = Field(..., description="Parent/guardian email address")
    parent_id: int = Field(..., description="Foreign key ID linking to the parent account in `users`")
    updated_at: datetime = Field(..., description="Last update UTC timestamp")

    model_config = ConfigDict(from_attributes=True)


class RewardDeleteResponse(BaseModel):
    message: str = Field(
        ...,
        description="Deletion confirmation message",
        examples=["Reward deleted successfully."],
    )
    reward_id: int = Field(..., description="ID of the deleted reward", examples=[1])
