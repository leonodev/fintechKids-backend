from __future__ import annotations

from datetime import datetime
from enum import Enum
from typing import Optional
from pydantic import BaseModel, ConfigDict, EmailStr, Field


class TaskStatusEnum(str, Enum):
    ENABLE = "enable"
    DISABLE = "disable"


class TaskCreate(BaseModel):
    name: str = Field(
        ...,
        min_length=1,
        max_length=255,
        description="Name of the task created by the parent",
        examples=["Clean the bedroom"],
    )
    time_granted: str = Field(
        ...,
        min_length=1,
        max_length=100,
        description="Screen/play time granted upon completing the task",
        examples=["00:30:00"],
    )
    coins_granted: int = Field(
        ...,
        ge=0,
        description="Amount of coins granted upon completing the task",
        examples=[50],
    )
    email_parent: EmailStr = Field(
        ...,
        description="Email address of the parent/guardian who owns the task",
        examples=["parent@fhk.app"],
    )
    description: str = Field(
        ...,
        min_length=1,
        description="Detailed description of the task to perform",
        examples=["Make the bed and put away all toys before dinner."],
    )
    status: TaskStatusEnum = Field(
        default=TaskStatusEnum.ENABLE,
        description="Initial task status (`enable` or `disable`). Defaults to `enable` automatically.",
        examples=["enable"],
    )


class TaskUpdate(BaseModel):
    name: Optional[str] = Field(
        default=None,
        min_length=1,
        max_length=255,
        description="New task name",
        examples=["Clean bedroom and desk"],
    )
    time_granted: Optional[str] = Field(
        default=None,
        min_length=1,
        max_length=100,
        description="New granted time",
        examples=["00:45:00"],
    )
    coins_granted: Optional[int] = Field(
        default=None,
        ge=0,
        description="New amount of granted coins",
        examples=[75],
    )
    description: Optional[str] = Field(
        default=None,
        min_length=1,
        description="New task description",
        examples=["Make the bed, put away toys, and organize the desk."],
    )
    status: Optional[TaskStatusEnum] = Field(
        default=None,
        description="New task status (`enable` to enable it or `disable` to disable it)",
        examples=["disable"],
    )


class TaskResponse(BaseModel):
    id: int = Field(..., description="Unique database ID of the task")
    created_at: datetime = Field(..., description="Creation UTC timestamp auto-generated by the backend")
    name: str = Field(..., description="Task name")
    time_granted: str = Field(..., description="Granted time")
    coins_granted: int = Field(..., description="Granted coins")
    email_parent: EmailStr = Field(..., description="Parent/guardian email address")
    description: str = Field(..., description="Task description")
    status: TaskStatusEnum = Field(..., description="Current task status (`enable` or `disable`)")
    parent_id: int = Field(..., description="Foreign key ID linking to the parent account in `users`")
    updated_at: datetime = Field(..., description="Last update UTC timestamp")

    model_config = ConfigDict(from_attributes=True)


class TaskDeleteResponse(BaseModel):
    message: str = Field(
        ...,
        description="Deletion confirmation message",
        examples=["Task deleted successfully."],
    )
    task_id: int = Field(..., description="ID of the deleted task", examples=[1])
